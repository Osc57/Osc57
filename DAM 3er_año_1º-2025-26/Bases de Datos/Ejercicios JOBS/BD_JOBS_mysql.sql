UPDATE CUENTA
    JOIN (
        SELECT COD_BANCO, COD_SUCUR, NUM_CTA, SUM(IMPORTE) AS TOTAL
        FROM   MOVIMIENTO
        WHERE  TIPO_MOV = 'R'
        GROUP  BY COD_BANCO, COD_SUCUR, NUM_CTA
    ) M ON CUENTA.COD_BANCO = M.COD_BANCO
       AND CUENTA.COD_SUCUR  = M.COD_SUCUR
       AND CUENTA.NUM_CTA    = M.NUM_CTA
SET CUENTA.SALDO_DEBE = M.TOTAL;

UPDATE CUENTA
    JOIN (
        SELECT COD_BANCO, COD_SUCUR, NUM_CTA, SUM(IMPORTE) AS TOTAL
        FROM   MOVIMIENTO
        WHERE  TIPO_MOV = 'I'
        GROUP  BY COD_BANCO, COD_SUCUR, NUM_CTA
    ) M ON CUENTA.COD_BANCO = M.COD_BANCO
       AND CUENTA.COD_SUCUR  = M.COD_SUCUR
       AND CUENTA.NUM_CTA    = M.NUM_CTA
SET CUENTA.SALDO_HABER = M.TOTAL;

UPDATE CUENTA SET SALDO_DEBE  = 0 WHERE SALDO_DEBE  IS NULL;
UPDATE CUENTA SET SALDO_HABER = 0 WHERE SALDO_HABER IS NULL;

